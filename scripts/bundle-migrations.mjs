/**
 * Concatenates supabase/migrations/*.sql into one file you can paste into the
 * Supabase SQL editor. Generated on demand so there is never a second copy of
 * the schema to keep in sync — the migrations stay the only source of truth.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const migrationsDir = path.join(process.cwd(), 'supabase', 'migrations');
const outFile = path.join(process.cwd(), 'supabase', 'migrations.bundle.sql');

const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();
if (files.length === 0) {
  console.error('No migrations found in supabase/migrations');
  process.exit(1);
}

const parts = [
  '-- TripMate :: all migrations, concatenated for the Supabase SQL editor.',
  '-- Generated by `npm run db:bundle` — do not edit; edit the migrations instead.',
  '-- Safe to run once on a fresh project. Re-running will fail on existing objects.',
  '',
  'begin;',
  '',
];

for (const file of files) {
  parts.push(`-- ${'='.repeat(74)}`, `-- ${file}`, `-- ${'='.repeat(74)}`, '');
  parts.push((await readFile(path.join(migrationsDir, file), 'utf8')).trim(), '');
}

parts.push('commit;', '');
await writeFile(outFile, parts.join('\n'), 'utf8');

console.log(`Wrote ${path.relative(process.cwd(), outFile)} from ${files.length} migrations:`);
for (const file of files) console.log(`  - ${file}`);
